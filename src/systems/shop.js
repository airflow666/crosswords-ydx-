/**
 * Бустеры и магазин.
 *
 * Прежде подсказка была одна и жила внутри партии: пять штук, первая бесплатно,
 * остальные за ролик. Теперь подсказок три вида, они лежат в общем инвентаре и
 * переносятся из партии в партию — иначе покупать их не имело бы смысла.
 *
 * --- Как посчитаны цены -------------------------------------------------
 *
 * За единицу полезности взята ОДНА открытая буква в том слове, над которым
 * игрок сейчас думает. Дальше каждый бустер оценён в этих единицах:
 *
 *   «Буква»   — ровно одна нужная буква                        = 1,0 ед.
 *   «Слово»   — целиком открытое слово (в среднем 5 букв) плюс
 *               снятый тупик: игрок не просто получает буквы, а
 *               закрывает определение, на котором застрял        = 6,0 ед.
 *   «Россыпь» — пять букв, но врассыпную по доске. За букву
 *               пользы меньше, чем от прицельной, зато сдвигает
 *               сразу несколько слов: 5 × 0,9                    = 4,5 ед.
 *
 * Наборы: 10 «букв» = 10 ед., 5 «слов» = 30 ед., 3 «россыпи» = 13,5 ед.
 * При цене 2,9 YAN за единицу выходит 29 / 87 / 39 — округляем до 29 / 89 / 39.
 * Общий набор стоит 53,5 ед. (155 YAN по отдельности) и продаётся за 119 —
 * скидка около четверти, заметная, но не обесценивающая одиночные покупки.
 *
 * Цены в коде — справочные, для показа до ответа платёжного API. Настоящие
 * берутся из каталога консоли: менять их там можно без пересборки игры.
 */

