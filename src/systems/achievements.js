/** Плоский список всех достижений с готовыми идентификаторами. */
export const ALL = GROUPS.flatMap((g) =>
  g.levels.map((lv, i) => ({
    id: `${g.id}.${i}`,
    group: g.id,
    groupTitle: g.title,
    icon: g.icon,
    style: g.style || 'normal',
    tier: Math.min(i, TIERS.length - 1),
    tierId: TIERS[Math.min(i, TIERS.length - 1)].id,
    title: lv.title,
    desc: lv.desc,
    goal: lv.goal,
  }))
);

export const TOTAL_COUNT = ALL.length;

const BY_ID = new Map(ALL.map((a) => [a.id, a]));

export function achievementById(id) {
  return BY_ID.get(id) || null;
}

/** Текущее значение группы по снимку прогресса. */
export function groupValue(groupId, snapshot) {
  const g = GROUPS.find((x) => x.id === groupId);
  return g ? g.value(snapshot) || 0 : 0;
}

/**
 * Все достижения, заслуженные при данном прогрессе. Считается «с нуля» каждый
 * раз — так задним числом закрываются и те, что игрок заработал до появления
 * этой системы, и те, что могли потеряться при сбое сохранения.
 */
export function earnedIds(snapshot) {
  const out = [];
  for (const g of GROUPS) {
    const v = g.value(snapshot) || 0;
    g.levels.forEach((lv, i) => {
      if (v >= lv.goal) out.push(`${g.id}.${i}`);
    });
  }
  return out;
}

/** Прогресс по конкретному достижению: сколько есть из скольких нужно. */
export function progressOf(achievement, snapshot) {
  const v = groupValue(achievement.group, snapshot);
  return { value: Math.min(v, achievement.goal), goal: achievement.goal, done: v >= achievement.goal };
}
