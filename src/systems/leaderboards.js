/**
 * Лидерборды: по числу достижений и по длине серии дней.
 *
 * Почему именно эти две таблицы. Соревноваться по времени решения в этой игре
 * невозможно — кроссворд у каждого свой, и сравнивать минуты на разных сетках
 * бессмысленно. А достижения и серия сравнимы честно: они про то, сколько
 * человек играл и насколько регулярно, а не про то, какая доска ему досталась.
 *
 * Таблицы заводятся в консоли разработчика с ЭТИМИ техническими именами.
 * Если их там нет, отправка тихо ничего не сделает: игра от этого не страдает.
 */

export const BOARDS = [
  {
    name: 'achievements',
    title: 'Достижения',
    icon: '🏆',
    unit: 'achievementForms',
    value: (saves) => saves.unlockedAchievements.length,
  },
  {
    name: 'streak',
    title: 'Серия дней',
    icon: '🔥',
    unit: 'dayForms',
    value: (saves) => saves.bestStreakDays,
  },
];

/**
 * Опубликовать оба результата.
 *
 * Вызывается после победы и после восстановления дня — то есть тогда, когда
 * значения могли измениться. Отправка не блокирует интерфейс: результат
 * лидерборда игрок увидит, когда откроет таблицу, и лишняя секунда ожидания
 * на экране победы ему не нужна.
 */
export function publishScores(sdk, saves) {
  if (!sdk) return;
  for (const b of BOARDS) {
    const v = b.value(saves);
    if (v > 0) sdk.submitScore(b.name, v);
  }
}
