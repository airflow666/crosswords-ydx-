/**
 * Игровые режимы — единственное место, где описано, чем они отличаются.
 *
 * Раньше режима не было вовсе: сложность выбиралась случайно из трёх размеров
 * сетки, а словарь был один. Теперь режим задаёт СРАЗУ ТРИ вещи — размер доски,
 * словарный пул и то, предпочитает ли генератор слова выше среднего.
 *
 * О сложности слов. Прежний словарь игры — бытовая лексика с прямыми
 * определениями («Домашний мурлыка»), это заметно легче того, что встречается в
 * обычном газетном кроссворде. Поэтому он целиком ушёл в ЛЁГКИЙ режим, а для
 * остальных написаны новые пулы: `pool.standard` — привычная кроссвордная
 * сложность, `pool.hard` — слова выше среднего, тематические паки — тоже
 * стандартного уровня, но внутри одной области.
 *
 * Прежде здесь стояло «ни один режим, кроме лёгкого, не берёт слова из старого
 * словаря». Правило пришлось ослабить, и вот почему. Замер на ОДНИХ И ТЕХ ЖЕ
 * шаблонах 9×9: словарь на 640 слов заполняет 1 доску из 60, на 1351 — 8, на
 * 4663 — 32. Успех сборки — прямая функция размера словаря, а из неё следует
 * всё остальное: и сколько времени генератор тратит на пустые попытки, и
 * насколько он свободен выбрать доску без недавно виденных слов. Пул из
 * восьмисот слов на сетку 11×11 не работал: игрок получал одни и те же слова
 * партию за партией.
 *
 * Поэтому СЛОВА из прежнего словаря в общие пулы теперь берутся — но только
 * слова. Определение к ним пишется заново, кроссвордным тоном: сложность
 * задаёт формулировка, а не сама лексема. «Домашний мурлыка» осталось в лёгком
 * пуле, в стандартный то же слово попадёт с другим определением или не попадёт
 * вовсе. Прямой перенос строки из старого словаря — по-прежнему нет.
 */

import { THEME_IDS, themeById } from './dict/index.js';

/**
 * Геометрия доски. Плотность чёрных клеток растёт вместе с размером: иначе на
 * большой сетке появляются слишком длинные слова, а словарь короткий.
 *
 * О `maxRun` — предельной длине слова. Раньше он везде равнялся шести, и
 * длинные слова в сетку не попадали вовсе: в одном только лёгком словаре
 * 959 семибуквенных, 502 восьмибуквенных и 236 девятибуквенных слов лежали
 * мёртвым грузом. Длинное слово — это и есть сложность кроссворда: у него
 * больше пересечений и его не подобрать перебором, поэтому предел растёт
 * вместе с доской.
 *
 * У тематических сеток предел ниже: словарь одной области заметно уже общего,
 * и на длинный слот кандидатов может просто не найтись.
 *
 * `attempts` — сколько раз генератор пробует собрать доску, прежде чем взять
 * лучшее из полученного. Число подобрано замером, а не на глаз: на 11×11 при
 * 120 попытках худший случай доходил до 1080 мс, при 25 — до 294 мс, и при этом
 * НИ ОДНА сетка не потеряла слов. Хвост попыток уходил в пустой перебор, а
 * секунда заблокированного потока на телефоне читается как зависшая игра.
 * У тематических сеток попыток больше: словарь одной области узкий, и запасные
 * заходы там действительно нужны.
 *
 * Важно: `maxRun` обязан быть МЕНЬШЕ размера доски. Если разрешить слово во всю
 * строку, шаблон перестаёт быть обязан ставить чёрные клетки, и доска
 * вырождается в полный словарный квадрат — сетку, где каждая строка и каждый
 * столбец разом являются словами. Такое почти никогда не собирается, и
 * backtracking уходит в многоминутный перебор (проверено на 7×7 при maxRun 7).
 */
export const GRIDS = {
  s7: { size: 7, maxRun: 6, black: 0.14, minWords: 8, attempts: 120 },
  s9: { size: 9, maxRun: 8, black: 0.16, minWords: 14, attempts: 70 },
  s11: { size: 11, maxRun: 9, black: 0.24, minWords: 18, attempts: 25 },
  t8: { size: 8, maxRun: 7, black: 0.22, minWords: 11, attempts: 120 },
  t7: { size: 7, maxRun: 6, black: 0.16, minWords: 8, attempts: 120 },
};

