export const MODE_IDS = Object.keys(MODES);

/** Тема дня: детерминированно от даты, чтобы у всех игроков она совпадала. */
export function themeOfDay(dateKey) {
  // Простая свёртка строки 'ГГГГ-ММ-ДД' в число. Криптостойкость тут не нужна —
  // нужна только одинаковость на всех устройствах и отсутствие явного цикла
  // «понедельник всегда природа».
  let h = 2166136261;
  for (let i = 0; i < dateKey.length; i++) {
    h ^= dateKey.charCodeAt(i);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return THEME_IDS[h % THEME_IDS.length];
}

/** Seed кроссворда дня — тот же у всех игроков и не меняется в течение суток. */
export function dailySeed(dateKey) {
  let h = 5381;
  for (let i = 0; i < dateKey.length; i++) h = ((h << 5) + h + dateKey.charCodeAt(i)) >>> 0;
  return h >>> 0;
}

/**
 * Развернуть «что играем» в параметры генерации.
 *
 * @param {{mode:string, theme?:string, dateKey?:string}} spec
 * @returns {{mode:string, theme:string|null, poolId:string, grids:object[],
 *            preferHard:boolean, title:string, icon:string}}
 */
export function resolveMode(spec) {
  const mode = MODES[spec.mode] ? spec.mode : 'easy';
  const cfg = MODES[mode];
  let themeId = null;
  let title = cfg.title;
  let icon = cfg.icon;

  if (mode === 'daily') {
    themeId = themeOfDay(spec.dateKey || '');
  } else if (mode === 'theme') {
    themeId = themeById(spec.theme) ? spec.theme : THEME_IDS[0];
  }

  const poolId = themeId ? `theme:${themeId}` : cfg.pool;
  if (themeId && mode === 'theme') {
    const th = themeById(themeId);
    title = th.title;
    icon = th.icon;
  }

  return {
    mode,
    theme: themeId,
    poolId,
    grids: cfg.grids.map((g) => GRIDS[g]),
    preferHard: cfg.preferHard,
    title,
    icon,
  };
}
