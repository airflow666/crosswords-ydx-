/** Ё→Е, верхний регистр — чтобы пересечения букв всегда совпадали. */
function normalize(word) {
  return word.toUpperCase().replace(/Ё/g, 'Е');
}

/**
 * Готовый словарь: массив { answer, clue }. answer нормализован.
 * Отфильтрованы записи с не-кириллицей и короче 3 букв, убраны дубли.
 */
const _seen = new Set();
export const DICTIONARY = RAW
  .map(({ a, c }) => ({ answer: normalize(a), clue: c }))
  .filter(({ answer }) => /^[А-Я]{3,}$/.test(answer))
  .filter(({ answer }) => {
    if (_seen.has(answer)) return false;
    _seen.add(answer);
    return true;
  });
