/** Ё→Е, верхний регистр — чтобы пересечения букв всегда совпадали. */
function normalize(word) {
  return word.toUpperCase().replace(/Ё/g, 'Е');
}

/**
 * Готовый словарь: массив { answer, clue, clues } — по одной записи на слово.
 * answer нормализован; записи с не-кириллицей и короче 3 букв отброшены.
 *
 * Одно слово может иметь НЕСКОЛЬКО определений (у многих слов есть разные
 * значения: НОС — орган и передняя часть судна, МОЛНИЯ — вспышка и застёжка).
 * Все варианты собираются в `clues`, и генератор выбирает один детерминированно
 * по сетке — так одно и то же слово в разных партиях приходит с разной
 * формулировкой. `clue` — первый вариант, для обратной совместимости.
 */
const _byAnswer = new Map();
for (const { a, c } of RAW) {
  const answer = normalize(a);
  if (!/^[А-Я]{3,}$/.test(answer)) continue;
  const clue = (c || '').trim();
  if (!clue) continue;
  let rec = _byAnswer.get(answer);
  if (!rec) { rec = { answer, clue, clues: [] }; _byAnswer.set(answer, rec); }
  if (!rec.clues.includes(clue)) rec.clues.push(clue);
}

