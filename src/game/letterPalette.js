/**
 * Палитра букв для выбранной клетки.
 *
 * Фишка ввода: вместо клавиатуры игрок при выборе клетки видит набор из
 * 8 букв — правильную + 7 правдоподобных отвлекающих. Это делает ввод
 * доступным для аудитории 30+ (крупные тап-цели, без набора), а
 * интеллектуальная нагрузка остаётся на разгадывании определений.
 *
 * Отвлекающие берутся из частотного распределения русских букв — чтобы они
 * выглядели правдоподобно «возможными в клетке», а не абсурдно.
 */

// Русские буквы по убыванию частоты в текстах (без Ё — нормализуется в Е).
const FREQ_ORDER = 'ОЕАИНТСРВЛКМДПУЯЫЬГЗБЧЙХЖШЮЦЩЭФЪ'.split('');

export const PALETTE_SIZE = 8;

/**
 * Построить палитру для правильной буквы.
 * @param {string} correct — правильная буква (верхний регистр, кириллица)
 * @param {RNG} rng — сеедируемый ГПСЧ (детерминизм в тестах)
 * @param {number} size — размер палитры (по умолчанию 8)
 * @returns {string[]} перемешанный массив из `size` уникальных букв, включающий correct
 */
export function buildPalette(correct, rng, size = PALETTE_SIZE) {
  const letters = new Set([correct]);
  // пул отвлекающих: частотные буквы кроме правильной
  const pool = FREQ_ORDER.filter((l) => l !== correct);
  rng.shuffle(pool);
  // слегка смещаем к более частым буквам: берём из первых двух третей чаще
  let idx = 0;
  while (letters.size < size && idx < pool.length) {
    letters.add(pool[idx++]);
  }
  return rng.shuffle([...letters]);
}
