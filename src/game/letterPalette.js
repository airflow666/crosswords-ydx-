/**
 * Палитра букв для активного слова.
 *
 * Один общий набор кнопок на ВСЁ выбранное слово (а не по 8 штук на каждую
 * клетку — так их получалось слишком много): все буквы самого слова
 * (с повторами, если буква встречается дважды) вперемешку с несколькими
 * случайными буквами, которых в слове нет. Игрок сам угадывает, какая буква
 * куда идёт — так вводить просто (не нужна клавиатура), но остаётся элемент
 * головоломки, а не бездумный тап по одной подсказанной букве на клетку.
 *
 * Лишние буквы берутся из частотного распределения русских букв, чтобы
 * выглядеть правдоподобно, а не абсурдно.
 */

// Русские буквы по убыванию частоты в текстах (без Ё — нормализуется в Е).
const FREQ_ORDER = 'ОЕАИНТСРВЛКМДПУЯЫЬГЗБЧЙХЖШЮЦЩЭФЪ'.split('');

// Сколько лишних (не из слова) букв добавлять к буквам самого слова.
export const EXTRA_LETTERS = 3;

/**
 * Построить палитру для слова целиком.
 * @param {string} word — правильное слово (верхний регистр, кириллица)
 * @param {RNG} rng — сеедируемый ГПСЧ (детерминизм между перерисовками)
 * @param {number} extra — сколько лишних букв добавить (по умолчанию 3)
 * @returns {string[]} перемешанный массив: буквы слова (с повторами) + лишние
 */
export function buildWordPalette(word, rng, extra = EXTRA_LETTERS) {
  const letters = word.split('');
  const owned = new Set(letters);
  const pool = FREQ_ORDER.filter((l) => !owned.has(l));
  rng.shuffle(pool);
  return rng.shuffle([...letters, ...pool.slice(0, extra)]);
}
